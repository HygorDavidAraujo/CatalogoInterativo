CREATE TABLE IF NOT EXISTS vinhos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    tipo VARCHAR(50) NOT NULL CHECK (tipo IN ('tinto', 'branco', 'rose', 'espumante', 'suco_integral_tinto', 'suco_integral_branco')),
    uva VARCHAR(255) NOT NULL,
    pais_origem VARCHAR(100),
    pais_codigo CHAR(2),
    bandeira_url VARCHAR(500),
    ano INTEGER NOT NULL,
    guarda VARCHAR(100),
    harmonizacao TEXT,
    descricao TEXT,
    preco NUMERIC(10, 2) NOT NULL,
    imagem VARCHAR(500),
    ativo BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS configuracoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave VARCHAR(100) UNIQUE,
    valor TEXT,
    nome_site VARCHAR(255),
    titulo VARCHAR(255),
    descricao TEXT,
    telefone VARCHAR(20),
    email VARCHAR(255),
    endereco TEXT,
    whatsapp VARCHAR(20),
    instagram VARCHAR(500),
    facebook VARCHAR(500),
    logo_url VARCHAR(500),
    destaque_vinho_id INTEGER,
    destaque_fixado_em TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo VARCHAR(255) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(255) UNIQUE NOT NULL,
    senha VARCHAR(255) NOT NULL,
    is_admin BOOLEAN DEFAULT FALSE,
    cpf VARCHAR(14) UNIQUE,
    logradouro VARCHAR(255),
    numero VARCHAR(10),
    complemento VARCHAR(255),
    bairro VARCHAR(100),
    cep VARCHAR(10),
    cidade VARCHAR(100),
    estado VARCHAR(2),
    is_vip BOOLEAN DEFAULT FALSE,
    vip_tipo VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessoes_usuario (
    id UUID PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    expira_em TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    total NUMERIC(10, 2) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'processando', 'enviado', 'entregue', 'cancelado')),
    observacoes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pedidos_itens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    vinho_id INTEGER NOT NULL,
    vinho_nome VARCHAR(255) NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10, 2) NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS beneficios_vip (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE,
    slug VARCHAR(255) NOT NULL UNIQUE,
    tipo_desconto VARCHAR(30) NOT NULL CHECK (tipo_desconto IN ('percentual', 'valor_fixo')),
    valor_desconto NUMERIC(10, 2) NOT NULL,
    cor VARCHAR(20),
    ordem INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS password_resets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token VARCHAR(128) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vinhos_ativo ON vinhos (ativo);
CREATE INDEX IF NOT EXISTS idx_vinhos_tipo ON vinhos (tipo);
CREATE INDEX IF NOT EXISTS idx_vinhos_pais ON vinhos (pais_origem, pais_codigo);
CREATE INDEX IF NOT EXISTS idx_vinhos_preco ON vinhos (preco);
CREATE INDEX IF NOT EXISTS idx_vinhos_ano ON vinhos (ano);
CREATE INDEX IF NOT EXISTS idx_usuarios_created_at ON usuarios (created_at);
CREATE INDEX IF NOT EXISTS idx_sessoes_usuario_id ON sessoes_usuario (usuario_id);
CREATE INDEX IF NOT EXISTS idx_sessoes_expira_em ON sessoes_usuario (expira_em);
CREATE INDEX IF NOT EXISTS idx_pedidos_usuario_id ON pedidos (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_status ON pedidos (status);
CREATE INDEX IF NOT EXISTS idx_pedidos_created_at ON pedidos (created_at);
CREATE INDEX IF NOT EXISTS idx_pedidos_itens_pedido_id ON pedidos_itens (pedido_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_itens_vinho_id ON pedidos_itens (vinho_id);
CREATE INDEX IF NOT EXISTS idx_password_resets_usuario_id ON password_resets (usuario_id);
CREATE INDEX IF NOT EXISTS idx_password_resets_expires_at ON password_resets (expires_at);

CREATE OR REPLACE FUNCTION atualizar_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION revogar_sessoes_usuario()
RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM sessoes_usuario WHERE usuario_id = NEW.id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS usuarios_revogar_sessoes ON usuarios;
CREATE TRIGGER usuarios_revogar_sessoes
AFTER UPDATE OF senha, is_admin ON usuarios
FOR EACH ROW
WHEN (OLD.senha IS DISTINCT FROM NEW.senha OR OLD.is_admin IS DISTINCT FROM NEW.is_admin)
EXECUTE FUNCTION revogar_sessoes_usuario();

DROP TRIGGER IF EXISTS vinhos_atualizar_updated_at ON vinhos;
CREATE TRIGGER vinhos_atualizar_updated_at BEFORE UPDATE ON vinhos
FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();

DROP TRIGGER IF EXISTS configuracoes_atualizar_updated_at ON configuracoes;
CREATE TRIGGER configuracoes_atualizar_updated_at BEFORE UPDATE ON configuracoes
FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();

DROP TRIGGER IF EXISTS usuarios_atualizar_updated_at ON usuarios;
CREATE TRIGGER usuarios_atualizar_updated_at BEFORE UPDATE ON usuarios
FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();

DROP TRIGGER IF EXISTS pedidos_atualizar_updated_at ON pedidos;
CREATE TRIGGER pedidos_atualizar_updated_at BEFORE UPDATE ON pedidos
FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();

DROP TRIGGER IF EXISTS beneficios_vip_atualizar_updated_at ON beneficios_vip;
CREATE TRIGGER beneficios_vip_atualizar_updated_at BEFORE UPDATE ON beneficios_vip
FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();

BEGIN;

CREATE TABLE IF NOT EXISTS notificacoes_pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER NOT NULL UNIQUE REFERENCES pedidos(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notificacoes_leituras (
    notificacao_id INTEGER NOT NULL REFERENCES notificacoes_pedidos(id) ON DELETE CASCADE,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    lida_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (notificacao_id, usuario_id)
);
CREATE INDEX IF NOT EXISTS idx_notificacoes_leituras_usuario ON notificacoes_leituras(usuario_id, notificacao_id);

CREATE TABLE IF NOT EXISTS push_inscricoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    sessao_id UUID NOT NULL REFERENCES sessoes_usuario(id) ON DELETE CASCADE,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_push_inscricoes_usuario ON push_inscricoes(usuario_id);

-- O registro da notificação participa da mesma transação que cria o pedido.
-- Pedidos anteriores à instalação da migração não geram avisos retroativos.
CREATE OR REPLACE FUNCTION registrar_notificacao_pedido() RETURNS TRIGGER AS $func$
BEGIN
    INSERT INTO notificacoes_pedidos (pedido_id) VALUES (NEW.id) ON CONFLICT (pedido_id) DO NOTHING;
    RETURN NEW;
END;
$func$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS pedidos_registrar_notificacao ON pedidos;
CREATE TRIGGER pedidos_registrar_notificacao AFTER INSERT ON pedidos
FOR EACH ROW EXECUTE FUNCTION registrar_notificacao_pedido();

COMMIT;
